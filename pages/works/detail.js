// URLパラメータから作品IDを取得
function getWorkIdFromURL() {
  const params = new URLSearchParams(window.location.search);
  return parseInt(params.get("id"));
}

// 作品データを取得
function getWorkById(id) {
  return works.find((work) => work.id === id);
}

// HTMLを動的に生成
function renderWorkDetail(work) {
  if (!work) {
    // 作品が見つからない場合
    document.querySelector(".work-detail-page .container").innerHTML = `
      <div style="text-align: center; padding: 100px 20px;">
        <h2>作品が見つかりませんでした</h2>
        <p style="margin-top: 20px;">
          <a href="../../index.html#works" class="button button-primary">作品一覧に戻る</a>
        </p>
      </div>
    `;
    return;
  }

  // ページタイトルを更新
  document.title = `${work.title} | allcamo`;

  // サムネイル部分
  const thumbnailHTML = `
    <div class="thumbnail">
      <img
        src="../../${work.image}"
        alt="${work.title}"
        class="tubasa_lp"
      />
      <p class="detail-title">${work.title}</p>
      ${work.isPersonal ? '<p class="is-personal">(自主制作)</p>' : ""}
    </div>
  `;

  // 担当領域のボタン
  const inChargeButtons = work.inCharge
    .map(
      (item) => `<div class="button button-secondary sns-button">${item}</div>`
    )
    .join("");

  // ジャンルのボタン
  const genreButtons = work.genreTags
    .map(
      (item) => `<div class="button button-secondary sns-button">${item}</div>`
    )
    .join("");

  // 使用ツールのボタン
  const toolButtons = work.tools
    .map(
      (item) => `<div class="button button-secondary sns-button">${item}</div>`
    )
    .join("");

  // 工夫・ポイントのタイムライン
  const pointsHTML = work.points
    .map(
      (point) => `
    <div class="timeline-item">
      <div class="about-timeline">${point.title}</div>
      <div class="about-timeline">${point.content}</div>
    </div>
  `
    )
    .join("");

  // カード部分
  const cardHTML = `
    <div class="contents detail-card">
      <div class="content-item">
        <h3 class="contact-heading">概要</h3>
        <p class="contact-email">${work.description}</p>
      </div>

      <div class="content-item">
        <h3 class="contact-heading">担当領域</h3>
        <div class="sns-buttons">${inChargeButtons}</div>
      </div>

      <div class="content-item">
        <h3 class="contact-heading">ジャンル</h3>
        <div class="sns-buttons">${genreButtons}</div>
      </div>

      <div class="content-item">
        <h3 class="contact-heading">使用ツール</h3>
        <div class="sns-buttons">${toolButtons}</div>
      </div>

      <div class="content-item">
        <h3 class="contact-heading">工夫・ポイント</h3>
        <div class="timeline">${pointsHTML}</div>
      </div>

      <div class="content-item">
        <h3 class="contact-heading">備考</h3>
        <p class="contact-email">${work.remarks}</p>
      </div>

      <div class="content-item">
        <h3 class="contact-heading">制作時期</h3>
        <p class="contact-email">${work.period}</p>
      </div>

      ${
        work.url
          ? `
      <div class="content-item">
        <h3 class="contact-heading">公開URL</h3>
        <p class="contact-email"><a href="${work.url}" target="_blank" rel="noopener noreferrer" style="color: var(--brown-dark); text-decoration: underline;">${work.url}</a></p>
      </div>
      `
          : ""
      }

${
  work.mockPc || work.mockSp // どちらか片方でもあればOK
    ? `
    <div class="content-item">
      <h3 class="contact-heading">画面を確認</h3>
      <div class="sns-buttons">
        ${
          work.mockPc
            ? `
        <a href="../../${work.mockPc}" 
           target="_blank" 
           rel="noopener noreferrer"
           class="button button-secondary sns-button">
          PC版を見る
        </a>
        `
            : ""
        }
        ${
          work.mockSp
            ? `
        <a href="../../${work.mockSp}" 
           target="_blank" 
           rel="noopener noreferrer"
           class="button button-secondary sns-button">
          スマホ版を見る
        </a>
        `
            : ""
        }
      </div>
    </div>
    `
    : ""
}
    </div>
  `;

  // コンテナに挿入（戻るボタンは既にHTMLに存在するので、その後に追加）
  const container = document.querySelector(".work-detail-page .container");

  // 既存のコンテンツをクリア（戻るボタン以外）
  Array.from(container.children).forEach((child) => {
    if (!child.classList.contains("back-button")) {
      child.remove();
    }
  });

  // 新しいコンテンツを追加
  container.insertAdjacentHTML("beforeend", thumbnailHTML + cardHTML);
}

